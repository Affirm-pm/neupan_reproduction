#pragma once

#include <concepts>
#include <optional>
#include <utility>

#include "finenav_core/plan/data_packet.hpp"
#include "finenav_msgs/msg/robot_state.hpp"
#include "geometry_msgs/msg/pose.hpp"

namespace finenav::core {

// =============================================================================
// PlanningContext — immutable per-frame data passed into Planner::plan().
//
// The framework assembles this from the Localizer (robot_state), the incoming
// action goal (goal_pose), and an optional reference trajectory (ref_traj)
// produced by an upstream planner in a pipeline chain. Planner authors consume
// these fields read-only; they do not need to know about the internal math
// representation (NavState<S>) used inside FineNavLocalizer.
// =============================================================================

template <typename PlannerT>
struct PlanningContext {
    finenav_msgs::msg::RobotState robot_state;  ///< Current robot state (pose / twist / accel)
    geometry_msgs::msg::Pose      goal_pose;
    InputDataT<PlannerT>          ref_traj;      // TODO: validate empty-trajectory logic
};

// =============================================================================
// PlannerConcept — the fundamental contract for motion generation algorithms.
//
// A Planner models a stateless algorithm that reads a map view and produces a
// trajectory:
// @f$ P : (State, Reference, MapView) \rightarrow Trajectory @f$
//
// ## Key Design Properties
//
// 1. **Trait introspection**: Each planner exposes `InputProfile` / `OutputProfile`
//    so the framework can compile-time select which DataPacket fields (pose, vel,
//    accel, time) are allocated. Planners that don't need reference trajectories
//    (e.g., pure-reactive controllers) can set `InputProfile::pose = false` to
//    save memory.
//
// 2. **Does NOT own maps**: Planners receive a lightweight `IMapView` adapter that
//    exposes only the subset of map data the algorithm actually needs. This enables
//    loose coupling, independent testing, and map-implementation-agnostic planner
//    code.
//
// 3. **Stateless across episodes**: `reset()` is called at episode boundaries (new
//    goal arrival), allowing planners to clear internal caches. Between `reset()`
//    calls the planner may retain state (e.g., MPPI warm-start samples).
//
// ## Required Interface
//
// Every Planner must expose:
// - `ConfigType`  — parameter struct (generated by generate_parameter_library)
// - `IMapView`    — inner class defining the map interface the planner needs
// - `InputDataT<T>` / `OutputDataT<T>` — resolved from IOProfile at compile time
// - `configure()` — apply runtime configuration (also used for dynamic reconfigure)
// - `reset()`     — clear episode-internal state
// - `plan(ctx, map_view)` — core algorithm; returns `std::optional<OutputDataT<Self>>`
// =============================================================================

template <typename T>
concept PlannerConcept =
    std::default_initializable<T> &&
    requires {
        typename T::ConfigType;
        typename T::IMapView;
        typename InputDataT<T>;
        typename OutputDataT<T>;
    } &&
    requires(T planner,
             const typename T::ConfigType& config,
             const PlanningContext<T>& ctx,
             const typename T::IMapView& map_view) {

        // --- Basic configuration ---
        { planner.configure(config) } -> std::same_as<void>;

        // --- Episode boundary: called by framework when a new goal arrives ---
        { planner.reset() } -> std::same_as<void>;

        // --- Core planning interface ---
        { planner.plan(ctx, map_view) } -> std::same_as<std::optional<OutputDataT<T>>>;
    };

}  // namespace finenav::core
